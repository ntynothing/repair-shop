CREATE TABLE IF NOT EXISTS users(
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 name TEXT NOT NULL,
 email TEXT NOT NULL UNIQUE,
 phone TEXT NOT NULL,
 password_hash TEXT NOT NULL,
 role TEXT NOT NULL CHECK(role IN('client','master','admin')),
 active INTEGER NOT NULL DEFAULT 1,
 created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS services(
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 name TEXT NOT NULL,
 description TEXT NOT NULL DEFAULT '',
 price_from REAL NOT NULL CHECK(price_from>=0),
 price_to REAL CHECK(price_to>=price_from)
);
CREATE TABLE IF NOT EXISTS requests(
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 client_id INTEGER NOT NULL REFERENCES users(id),
 master_id INTEGER REFERENCES users(id),
 device_type TEXT NOT NULL,
 model TEXT NOT NULL,
 fault TEXT NOT NULL,
 problem TEXT NOT NULL,
 photo TEXT,
 status TEXT NOT NULL DEFAULT 'Принята',
 work_cost REAL NOT NULL DEFAULT 0 CHECK(work_cost>=0),
 created_at TEXT NOT NULL,
 updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS comments(
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 request_id INTEGER NOT NULL REFERENCES requests(id) ON DELETE CASCADE,
 user_id INTEGER NOT NULL REFERENCES users(id),
 text TEXT NOT NULL,
 created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS parts(
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 name TEXT NOT NULL,
 sku TEXT NOT NULL UNIQUE,
 quantity INTEGER NOT NULL DEFAULT 0 CHECK(quantity>=0),
 min_qty INTEGER NOT NULL DEFAULT 2,
 price REAL NOT NULL CHECK(price>=0)
);
CREATE TABLE IF NOT EXISTS request_parts(
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 request_id INTEGER NOT NULL REFERENCES requests(id) ON DELETE CASCADE,
 part_id INTEGER NOT NULL REFERENCES parts(id) ON DELETE RESTRICT,
 qty INTEGER NOT NULL CHECK(qty>0)
);
